export const GRID_COLS = 16;
export const GRID_ROWS = 3;

export function placeCardsInGrid(cardIds: number[]): (number | null)[][] {
  const shuffled = shuffleArray([...cardIds]);
  const grid: (number | null)[][] = Array.from({ length: GRID_ROWS }, () =>
    Array.from({ length: GRID_COLS }, () => null)
  );
  const rowCounts = [10, 8, 7];
  let idx = 0;
  for (let r = 0; r < GRID_ROWS; r++) {
    const count = rowCounts[r];
    const leftCount = Math.ceil(count / 2);
    const rightCount = count - leftCount;
    for (let c = 0; c < leftCount && idx < shuffled.length; c++) {
      grid[r][c] = shuffled[idx++];
    }
    for (let c = 0; c < rightCount && idx < shuffled.length; c++) {
      grid[r][GRID_COLS - 1 - c] = shuffled[idx++];
    }
  }
  return grid;
}

export function splitTextIntoColumns(text: string): string[] {
  const raw = text.replace(/\s+/g, "");
  const len = raw.length;
  const colSize = Math.ceil(len / 3);
  const cols: string[] = [];
  for (let i = 0; i < len; i += colSize) {
    cols.push(raw.slice(i, i + colSize));
  }
  while (cols.length < 3) cols.push("");
  return cols;
}

export function shuffleArray<T>(array: T[]): T[] {
  const arr = [...array];
  for (let i = arr.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [arr[i], arr[j]] = [arr[j], arr[i]];
  }
  return arr;
}

export function splitIntoRows(cardIds: number[], rowSizes: number[]): number[][] {
  const result: number[][] = [];
  let idx = 0;
  for (const size of rowSizes) {
    result.push(cardIds.slice(idx, idx + size));
    idx += size;
  }
  return result;
}
